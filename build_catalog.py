def classify(dsid):
    """Return (branch, collection_id, collection_title, product_type, extra)."""
    if dsid in OBSERVATIONS:
        return "observations", OBSERVATIONS[dsid], OBSERVATIONS[dsid], "observation", {}
    if dsid in REANALYSES:
        return "reanalyses", REANALYSES[dsid], REANALYSES[dsid], "reanalysis", {}
    if dsid in DERIVED:
        feature, tracker = DERIVED[dsid]
        return f"derived/{feature.upper()}-tracks", tracker, tracker, "derived", {"km_scale:feature": feature}
    for prefix, coll, title in MODEL_PREFIXES:
        if dsid.startswith(prefix):
            return "simulations", coll, title, "simulation", {}
    raise ValueError(f"unclassified id {dsid}")


def infer_experiment(dsid, meta):
    s = dsid.lower()
    if "p4k" in s:
        return "dyamond3-p4k"
    for e in ("dyamond1", "dyamond2", "dyamond3"):
        if e in s:
            return e
    start, end = str(meta.get("time_start", ""))[:10], str(meta.get("time_end", ""))[:10]
    if start and end and start <= "2020-01-20" and end >= "2021-02-28":  # covers the DYAMOND3 period
        return "dyamond3"
    return "other"


def infer_domain(dsid, meta):
    if meta.get("region", "global") not in ("global", None) or any(h in dsid for h in REGIONAL_HINTS):
        return "regional"
    return "global"


SPDX = {
    "cc-by-4.0": "CC-BY-4.0", "cc by 4.0": "CC-BY-4.0", "cc-by 4.0": "CC-BY-4.0", "cc-by-sa-4.0": "CC-BY-SA-4.0",
    "cc0": "CC0-1.0", "cc-by-nc-4.0": "CC-BY-NC-4.0",
}


def map_license(text):
    if not text:
        return None
    t = str(text).strip().lower()
    for k, v in SPDX.items():
        if t == k or t.startswith(k + " ") or t.startswith(k + ","):
            return v
    return "other"


# --- reading and expanding the HK25 catalogue ------------------------------------------------------------------------
def load_hk25(root):
    entries = defaultdict(dict)  # id -> node -> entry
    for f in sorted(root.glob("*/main.yaml")):
        node = f.parent.name
        for k, v in (yaml.safe_load(f.read_text()).get("sources") or {}).items():
            entries[k][node] = v
    return entries


def expand(entry):
    """Yield (params, [urls]) for every combination of allowed parameter values, as Intake would render them."""
    ps = entry.get("parameters") or {}
    names = list(ps)
    choices = [ps[p].get("allowed", [ps[p].get("default")]) for p in names]
    u = entry["args"]["urlpath"]
    us = u if isinstance(u, list) else [u]
    for combo in itertools.product(*choices):
        ctx = dict(zip(names, combo))
        yield ctx, [jinja2.Template(x).render(**ctx).strip() for x in us]


def asset_keys(params, urls):
    """Asset key per URL: '<other params>.z<zoom>'; a second URL that is a static store gets 'static.z<zoom>'."""
    zoom = params.get("zoom")
    rest = [str(params[k]) for k in params if k != "zoom"]
    base = "_".join(rest) if rest else "data"
    z = f".z{zoom}" if zoom is not None else ""
    keys = []
    for i, u in enumerate(urls):
        if i == 0:
            keys.append(base + z)
        elif "static" in u:
            keys.append("static" + z)
        else:
            keys.append(f"{base}_part{i + 1}{z}")
    return keys


def media_type(url, driver):
    if url.startswith("reference::"):
        return "application/vnd.apache.parquet", "kerchunk"
    if driver == "netcdf" or url.endswith(".nc") or "*" in url and not url.rstrip("/").endswith(".zarr"):
        return "application/x-netcdf", "netcdf"
    return "application/vnd.zarr; version=2", "zarr"


# --- consolidated metadata -> datacube --------------------------------------------------------------------------------
def fetch_json(url, timeout=20):
    try:
        with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "stac-prototype"}),
                                    timeout=timeout) as r:
            return json.load(r)
    except (urllib.error.URLError, TimeoutError, ValueError, OSError):
        return None


def read_zmeta(url):
    """Return (zarr_format, {array_name: (attrs, shape, dtype, dims)}) or None if unreachable."""
    url = url.rstrip("/")
    zm = fetch_json(url + "/.zmetadata")
    if zm is not None:
        meta = zm.get("metadata", {})
        arrays = {}
        for key, v in meta.items():
            if key.endswith("/.zarray"):
                name = key[: -len("/.zarray")]
                if "/" in name:
                    continue
                attrs = meta.get(f"{name}/.zattrs", {})
                arrays[name] = (attrs, v.get("shape", []), v.get("dtype"), attrs.get("_ARRAY_DIMENSIONS", []))
        return 2, arrays, meta.get(".zattrs", {})
    zj = fetch_json(url + "/zarr.json")
    if zj is not None:
        arrays = {}
        for name, v in (zj.get("consolidated_metadata") or {}).get("metadata", {}).items():
            if v.get("node_type") == "array" and "/" not in name:
                arrays[name] = (v.get("attributes", {}), v.get("shape", []), v.get("data_type"),
                                v.get("dimension_names") or [])
        return 3, arrays, zj.get("attributes", {})
    return None


VERTICAL_NAMES = {"pressure", "plev", "level", "lev", "height", "depth", "pressure_level", "isobaricinhpa"}
DTYPES = {"<f4": "float32", "<f8": "float64", "<i4": "int32", "<i8": "int64", "|i1": "int8", "<i2": "int16",
          "|u1": "uint8", "<u2": "uint16", "|b1": "bool", "<M8[ns]": "datetime64[ns]"}


def read_coords(url, dims):
    """Read small coordinate arrays (levels; first and last time) from one store. Returns {dim: values}."""
    import numpy as np
    import xarray as xr
    try:
        ds = xr.open_zarr(url, consolidated=True, decode_times=True, chunks=None)
    except Exception:
        return {}
    out = {}
    for d in dims:
        if d not in ds.coords and d not in ds.variables:
            continue
        c = ds[d]
        if c.ndim != 1:
            continue
        try:
            if np.issubdtype(c.dtype, np.datetime64):
                v = c.values[[0, -1]] if c.size > 1 else c.values
                out[d] = [str(np.datetime_as_string(x, unit="s")) + "Z" for x in v]
            elif c.size <= 1000 and np.issubdtype(c.dtype, np.number):
                out[d] = [float(str(x)) if np.issubdtype(c.dtype, np.floating) else int(x) for x in c.values]  # str(): float32 without noise
        except Exception:
            pass
    return out


def datacube(zmeta, zoom, freq, meta, coords=None):
    coords = coords or {}
    fmt, arrays, _ = zmeta
    dim_sizes, dims = {}, {}
    for name, (attrs, shape, dtype, adims) in arrays.items():
        for d, n in zip(adims, shape):
            dim_sizes[d] = n
    for d, n in dim_sizes.items():
        attrs = arrays.get(d, ({},))[0]
        sn = attrs.get("standard_name", "")
        if d == "time" or sn == "time":
            o = {"type": "temporal"}
            if d in coords and coords[d]:
                o["extent"] = [coords[d][0], coords[d][-1]]  # from the data
            elif meta.get("time_start") and meta.get("time_end"):
                o["extent"] = [iso(meta["time_start"]), iso(meta["time_end"])]
            if freq and re.fullmatch(r"P(T\d+[HM]|\d+[DM])", str(freq)):
                o["step"] = freq
        elif zoom is not None and n == 12 * 4 ** int(zoom):
            o = {"type": "healpix", "extent": [0, n - 1], "count": n,
                 "description": f"HEALPix nested, refinement level {zoom} (HK25: spherical)"}
        elif d.lower() in VERTICAL_NAMES or sn in ("air_pressure", "height", "depth", "model_level_number"):
            o = {"type": "spatial", "axis": "z", "count": n}
        else:
            o = {"type": "other", "count": n}
        if o["type"] in ("spatial", "other"):
            vals = coords.get(d)
            if vals:
                o["values"] = vals
            else:
                o["extent"] = [0, n - 1]  # index range: no coordinate values in the store
                o["description"] = "index (no coordinate values in store)"
        if attrs.get("units") and o["type"] != "temporal":
            o["unit"] = attrs["units"]
        dims[d] = o
    variables = {}
    for name, (attrs, shape, dtype, adims) in arrays.items():
        if name in dim_sizes:
            continue
        v = {"dimensions": list(adims), "type": "data" if len(adims) > 1 or "time" in adims else "auxiliary"}
        for src, dst in (("units", "unit"), ("long_name", "description"), ("standard_name", "cf:standard_name")):
            if attrs.get(src):
                v[dst] = attrs[src]
        if attrs.get("cell_methods"):
            v["cf:cell_methods"] = [attrs["cell_methods"]]  # array form: the cf v1.0.0 schema rejects the README's plain string
        if isinstance(dtype, str):
            v["data_type"] = DTYPES.get(dtype, dtype)
        variables[name] = v
    return dims, variables


def iso(t):
    t = str(t).strip().replace(" ", "T")
    if len(t) == 10:
        t += "T00:00:00"
    if re.fullmatch(r".*T\d\d:\d\d", t):
        t += ":00"
    return t if t.endswith("Z") else t + "Z"


# --- building ---------------------------------------------------------------------------------------------------------
def apply_override(href, site, sites):
    for a, b in (sites.get(site) or {}).get("endpoint_overrides", {}).items():
        if href.startswith(a):
            return b + href[len(a):]
    return href


def build(hk25_root, out, probe=True):
    sites = yaml.safe_load((HERE / "config/sites.yaml").read_text())
    vocab = yaml.safe_load((HERE / "config/vocab.yaml").read_text())
    entries = load_hk25(hk25_root)
    problems = []

    # 1. expand every entry at every node into assets
    items = {}
    for dsid, nodes in sorted(entries.items()):
        meta = max((v.get("metadata") or {} for v in nodes.values()), key=len)
        branch, coll, coll_title, ptype, extra = classify(dsid)
        driver = next(iter(nodes.values())).get("driver")
        consolidated = next(iter(nodes.values()))["args"].get("consolidated")
        per_node = {}  # node -> {asset key: (url, params)}
        for node, e in nodes.items():
            d = {}
            for params, urls in expand(e):
                for k, u in zip(asset_keys(params, urls), urls):
                    d[k] = (u, params)
            per_node[node] = d
        default_node = "online" if "online" in per_node else sorted(per_node)[0]
        assets = {}
        for key, (url, params) in per_node[default_node].items():
            mt, fmt = media_type(url, driver)
            a = {"href": url, "type": mt, "roles": ["data"], "title": key}
            if fmt == "zarr" and consolidated is not None:
                a["zarr:consolidated"] = bool(consolidated)
            if fmt != "zarr":
                a["km_scale:format"] = fmt
            if "zoom" in params:
                a["km_scale:zoom"] = int(params["zoom"])
            alt = {}
            for node, d in per_node.items():
                if node == default_node or key not in d:
                    continue
                site_url = d[key][0]
                if default_node == "online" and apply_override(url, node, sites) == site_url:
                    continue  # same objects through the site's own endpoint: covered by the site table
                alt[node] = {"href": site_url}
            if alt:
                a["alternate"] = alt
            assets[key] = a
        # keys present at a site but not at the default location
        for node, d in per_node.items():
            for key in d.keys() - assets.keys():
                problems.append(f"{dsid}: asset {key} only at {node}, not at {default_node}")
        props = {
            "title": meta.get("title") or dsid,
            "description": (meta.get("summary") or "").strip() or None,
            "datetime": None,
            "start_datetime": iso(meta["time_start"]) if meta.get("time_start") else None,
            "end_datetime": iso(meta["time_end"]) if meta.get("time_end") else None,
            "license": map_license(meta.get("license")),
            "providers": [{"name": meta["institution"], "roles": ["producer"]}] if meta.get("institution") else None,
            "km_scale:product_type": ptype,
            "km_scale:experiment": infer_experiment(dsid, meta) if ptype == "simulation" else None,
            "km_scale:experiment_inferred": True if ptype == "simulation" else None,  # HK25 has no such field
            "km_scale:domain": infer_domain(dsid, meta),
            "km_scale:source_id": meta.get("source_id"),
            "km_scale:resolution": meta.get("resolution"),
            "km_scale:sites": sorted(per_node),
            "km_scale:creators": meta.get("creator_name"),
            "km_scale:references": meta.get("references") or meta.get("citation"),
            "km_scale:license_text": meta.get("license") if map_license(meta.get("license")) == "other" else None,
            **extra,
        }
        if "online" not in per_node:
            props["km_scale:site_only"] = sorted(per_node)
        if not props["start_datetime"] or not props["end_datetime"]:
            props["datetime"] = "2020-01-20T00:00:00Z"  # STAC needs a time; placeholder, flagged below
            props.pop("start_datetime"), props.pop("end_datetime")
            problems.append(f"{dsid}: no time_start/time_end in metadata; placeholder datetime")
        if not props["license"]:
            props["license"] = "other"
            problems.append(f"{dsid}: no licence in metadata")
        props = {k: v for k, v in props.items() if v is not None}
        domain_regional = props["km_scale:domain"] == "regional"
        lon = [meta.get("geospatial_lon_min"), meta.get("geospatial_lon_max")]
        lat = [meta.get("geospatial_lat_min"), meta.get("geospatial_lat_max")]
        if domain_regional and None not in lon + lat:
            bbox = [float(lon[0]), float(lat[0]), float(lon[1]), float(lat[1])]
            geom = {"type": "Polygon", "coordinates": [[[bbox[0], bbox[1]], [bbox[2], bbox[1]], [bbox[2], bbox[3]],
                                                       [bbox[0], bbox[3]], [bbox[0], bbox[1]]]]}
        else:
            bbox, geom = GLOBAL_BBOX, GLOBAL_GEOM
        items[dsid] = {"branch": branch, "coll": coll, "coll_title": coll_title, "props": props, "assets": assets,
                       "bbox": bbox, "geometry": geom, "meta": meta}
        # vocabulary check
        for field in ("product_type", "experiment", "domain", "feature"):
            v = props.get(f"km_scale:{field}")
            if v is not None and v not in vocab[field]:
                problems.append(f"{dsid}: km_scale:{field}={v!r} not in vocab")

    # 2. probe online stores: existence for every asset, datacube from the coarsest zoom of each frequency
    if probe:
        jobs = {}
        for dsid, it in items.items():
            for key, a in it["assets"].items():
                if a["href"].startswith("http") and a.get("km_scale:format") is None and "*" not in a["href"]:
                    jobs[(dsid, key)] = a["href"]
        print(f"probing {len(jobs)} online Zarr assets ...", file=sys.stderr)
        with cf.ThreadPoolExecutor(48) as ex:
            res = dict(zip(jobs, ex.map(read_zmeta, jobs.values())))
        # coordinate values from the coarsest zoom of each frequency group
        groups = defaultdict(list)
        for (dsid, key), zm in res.items():
            if zm is not None:
                groups[(dsid, key.split(".")[0])].append((items[dsid]["assets"][key].get("km_scale:zoom", 0), key, zm))
        cjobs = {}
        for g, lst in groups.items():
            z, key, zm = min(lst)
            dims = {d for (_, _, _, adims) in zm[1].values() for d in adims}
            cjobs[g] = (items[g[0]]["assets"][key]["href"], dims)
        print(f"reading coordinates from {len(cjobs)} stores ...", file=sys.stderr)
        with cf.ThreadPoolExecutor(16) as ex:
            coords = dict(zip(cjobs, ex.map(lambda j: read_coords(*j), cjobs.values())))
        for (dsid, key), zm in res.items():
            a = items[dsid]["assets"][key]
            if zm is None:
                a["km_scale:reachable"] = False
                problems.append(f"{dsid}: {key} not reachable at {a['href']}")
                continue
            a["zarr:zarr_format"] = zm[0]
            if zm[0] == 3:
                a["type"] = "application/vnd.zarr; version=3"
            freq = key.split(".")[0].split("_")[0]
            dims, variables = datacube(zm, a.get("km_scale:zoom"), freq, items[dsid]["meta"],
                                       coords.get((dsid, key.split(".")[0])))
            a["cube:dimensions"], a["cube:variables"] = dims, variables

    # 3. write the tree
    if out.exists():
        shutil.rmtree(out)
    stac = out / "stac"
    colls = defaultdict(list)
    for dsid, it in items.items():
        colls[(it["branch"], it["coll"])].append(dsid)

    def write(path, obj):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(obj, indent=1))

    def rel(frm, to):
        import os
        return os.path.relpath(to, frm.parent)

    root_path = stac / "catalog.json"
    branch_children = defaultdict(list)
    index = []
    for (branch, coll), ids in sorted(colls.items()):
        cpath = stac / branch / coll / "collection.json"
        branch_children[branch].append(cpath)
        lic = {items[i]["props"]["license"] for i in ids}
        times = [(items[i]["props"].get("start_datetime"), items[i]["props"].get("end_datetime")) for i in ids]
        starts = sorted(t[0] for t in times if t[0])
        ends = sorted(t[1] for t in times if t[1])
        exts = set()
        links = [{"rel": "root", "href": rel(cpath, root_path), "type": "application/json"},
                 {"rel": "parent", "href": rel(cpath, stac / branch / "catalog.json"), "type": "application/json"},
                 {"rel": "self", "href": f"{branch}/{coll}/collection.json"}]
        for dsid in sorted(ids):
            it = items[dsid]
            ipath = stac / branch / coll / dsid / f"{dsid}.json"
            stac_ext = [EXT["alternate"], EXT["zarr"]]
            if any("cube:dimensions" in a for a in it["assets"].values()):
                stac_ext += [EXT["datacube"], EXT["cf"]]
            ilinks = [{"rel": "root", "href": rel(ipath, root_path), "type": "application/json"},
                      {"rel": "parent", "href": rel(ipath, cpath), "type": "application/json"},
                      {"rel": "collection", "href": rel(ipath, cpath), "type": "application/json"}]
            if it["props"]["license"] == "other" and it["props"].get("km_scale:license_text"):
                ilinks.append({"rel": "license", "href": "https://digital-earths-global-hackathon.github.io/catalog/",
                               "title": it["props"]["km_scale:license_text"][:200]})
            if it["props"]["km_scale:product_type"] == "derived":
                stac_ext.append(EXT["processing"])
                it["props"]["processing:software"] = {it["coll"]: "unknown"}
            write(ipath, {"type": "Feature", "stac_version": STAC_VERSION, "stac_extensions": sorted(set(stac_ext)),
                          "id": dsid, "collection": coll, "geometry": it["geometry"], "bbox": it["bbox"],
                          "properties": it["props"], "assets": it["assets"], "links": ilinks})
            exts.update(stac_ext)
            links.append({"rel": "item", "href": rel(cpath, ipath), "type": "application/geo+json"})
            variables = sorted({v for a in it["assets"].values() for v, d in a.get("cube:variables", {}).items()
                                if d.get("type") == "data"})
            freqs = sorted({k.split(".")[0] for k in it["assets"]})
            zooms = sorted({a["km_scale:zoom"] for a in it["assets"].values() if "km_scale:zoom" in a})
            p = it["props"]
            index.append({
                "id": dsid, "title": p["title"], "collection": coll, "branch": branch, "path": f"{branch}/{coll}",
                "product_type": p["km_scale:product_type"], "experiment": p.get("km_scale:experiment"),
                "domain": p["km_scale:domain"], "source_id": p.get("km_scale:source_id"),
                "resolution": p.get("km_scale:resolution"), "start": p.get("start_datetime"),
                "end": p.get("end_datetime"), "license": p["license"], "license_text": p.get("km_scale:license_text"),
                "sites": p["km_scale:sites"], "site_only": p.get("km_scale:site_only"), "frequencies": freqs,
                "zooms": zooms, "variables": variables, "description": (p.get("description") or "")[:600],
                "item": str(ipath.relative_to(out)),
                "gridlook": gridlook(it),
            })
        summ = {"km_scale:experiment": sorted({items[i]["props"].get("km_scale:experiment") for i in ids} - {None}),
                "km_scale:domain": sorted({items[i]["props"]["km_scale:domain"] for i in ids})}
        summ = {k: v for k, v in summ.items() if v}  # empty summaries are invalid STAC
        provs = sorted({pr["name"] for i in ids for pr in items[i]["props"].get("providers", [])})
        write(cpath, {
            "type": "Collection", "stac_version": STAC_VERSION, "stac_extensions": [], "id": coll,
            "title": items[ids[0]]["coll_title"],
            "description": f"{items[ids[0]]['coll_title']} datasets from the HK25 catalogue ({len(ids)} Items).",
            "license": lic.pop() if len(lic) == 1 else "other",
            "extent": {"spatial": {"bbox": [GLOBAL_BBOX]},
                       "temporal": {"interval": [[starts[0] if starts else None, ends[-1] if ends else None]]}},
            "summaries": summ, "links": links,
            **({"providers": [{"name": n, "roles": ["producer"]} for n in provs]} if provs else {})})

    # branch catalogs (simulations, observations, reanalyses, derived/<feature>-tracks under derived)
    def catalog(path, cid, title, desc, children, items_links=()):
        links = [{"rel": "root", "href": rel(path, root_path), "type": "application/json"}]
        if path != root_path:
            links.append({"rel": "parent", "href": rel(path, path.parent.parent / "catalog.json"),
                          "type": "application/json"})
        links += [{"rel": "child", "href": rel(path, c), "type": "application/json"} for c in children]
        links += [{"rel": "item", "href": rel(path, i), "type": "application/geo+json"} for i in items_links]
        write(path, {"type": "Catalog", "stac_version": STAC_VERSION, "id": cid, "title": title,
                     "description": desc, "links": links})

    top = []
    derived_children = []
    for branch, children in sorted(branch_children.items()):
        p = stac / branch / "catalog.json"
        name = branch.split("/")[-1]
        catalog(p, branch.replace("/", "-"), name, BRANCH_DESCRIPTIONS.get(name, f"{name} datasets"), children)
        if branch.startswith("derived/"):
            derived_children.append(p)
        else:
            top.append(p)
    if derived_children:
        p = stac / "derived" / "catalog.json"
        catalog(p, "derived", "derived", "Products derived from other datasets (e.g. feature tracks).",
                derived_children)
        top.append(p)
    # generated by-experiment views: item links only, Items stay where they are
    exp_children = []
    by_exp = defaultdict(list)
    for e in index:
        if e["experiment"]:
            by_exp[e["experiment"]].append(stac.parent / e["item"])
    for exp, ipaths in sorted(by_exp.items()):
        p = stac / "by-experiment" / exp / "catalog.json"
        catalog(p, f"by-experiment-{exp}", exp, vocab["experiment"][exp], [], sorted(ipaths))
        exp_children.append(p)
    p = stac / "by-experiment" / "catalog.json"
    catalog(p, "by-experiment", "by experiment", "Generated views: links to Items, grouped by experiment.",
            exp_children)
    top.append(p)
    ORDER = ["simulations", "observations", "reanalyses", "derived", "by-experiment"]
    top.sort(key=lambda c: ORDER.index(c.parent.name) if c.parent.name in ORDER else 99)
    catalog(root_path, "km-scale-hk25-example", "HK25 catalogue as STAC (HK27 prototype)",
            "Example static STAC catalogue generated from the HK25 Intake catalogue.", top)

    # tree for the page, generated from the STAC links so the two can't disagree (by-experiment views left out)
    def node(path):
        d = json.loads(path.read_text())
        n = {"id": d["id"], "title": d.get("title") or d["id"], "type": d["type"],
             "path": str(path.parent.relative_to(stac.resolve())), "href": str(path.relative_to(out.resolve())),
             "description": d.get("description")}
        for k in ("license", "summaries", "providers", "extent"):
            if k in d:
                n[k] = d[k]
        kids = [path.parent / l["href"] for l in d["links"] if l["rel"] == "child"]
        n["children"] = [node(c.resolve()) for c in kids if "by-experiment" not in str(c)]
        return n
    (out / "tree.json").write_text(json.dumps(node(root_path.resolve()), indent=0))

    # 4. index, site table, problems, page
    (out / "index.json").write_text(json.dumps(index, indent=0))
    shutil.copy(HERE / "config/sites.yaml", out / "sites.yaml")
    (out / "sites.json").write_text(json.dumps(sites, indent=1))
    (out / "problems.txt").write_text("\n".join(problems) + "\n")
    shutil.copy(HERE / "page/index.html", out / "index.html")
    shutil.copy(HERE / "km_scale.py", out / "km_scale.py")
    n_assets = sum(len(it["assets"]) for it in items.values())
    n_cube = sum("cube:variables" in a for it in items.values() for a in it["assets"].values())
    print(f"{len(items)} Items in {len(colls)} Collections, {n_assets} assets ({n_cube} with datacube), "
          f"{len(problems)} problems (see problems.txt)", file=sys.stderr)
    print(Counter(e["experiment"] for e in index), file=sys.stderr)


def gridlook(it):
    if it["props"]["km_scale:domain"] != "global":
        return None
    cands = [(abs(a.get("km_scale:zoom", 99) - 7), k, a) for k, a in it["assets"].items()
             if a["href"].startswith("http") and a.get("km_scale:reachable", True) and a.get("km_scale:format") is None
             and not k.startswith("static")]
    return min(cands)[2]["href"] if cands else None


