"""Build an example static STAC catalogue from the HK25 Intake catalogue.

Experiment for HK27: one catalogue (no per-site catalogues, no merging at read time), assets per frequency and zoom,
site copies as alternate assets, a site table for network-level rules, datacube + cf from consolidated Zarr metadata,
a controlled vocabulary check, generated by-experiment views, a flat search index and a static search page.

    uv run build_catalog.py ~/projects/external/hk25/catalog build/

HK25 stores are one store per zoom (HK27 will have zoom groups in one store), so assets are keyed
"<freq>.z<zoom>" here; HK27 would key them "<freq>" and record the zoom levels on the asset.
"""

